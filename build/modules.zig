//! Declare the module graph as data: what modules exist, and which imports which.
//!
//! Lifted out of build.zig's `build()`, which had grown to 2085 lines with ~480 of them
//! being these two tables. They are pure data with no dependency on the `*std.Build` -- the
//! only reason they lived inside the function is that they were written there. build.zig
//! now creates the modules and wires the edges from these tables and nothing else changes.
//!
//! TWO TOOLS PARSE THIS FILE AS TEXT, and neither can be moved off it cheaply:
//! `tools/arch_report.zig` splits on `.{ .name = "` to recover the graph nodes and reads
//! the edge table for its DAG/NCCD report, and `tools/headless_lint.sh` greps
//! `.name = .. .path = ..` to map each module to its zone. Both were pointed here in the
//! same commit that moved the tables. If a future change reshapes these literals, those two
//! go QUIETLY VACUOUS rather than red -- arch-report would report an empty graph and still
//! exit 0 -- so re-run both and compare the node/edge counts, never just the exit code.

